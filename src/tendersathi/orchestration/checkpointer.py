"""Postgres-backed LangGraph checkpointer -- the only place that opens this connection.

Checkpointing is what lets the pipeline survive the human-approval
interrupt across separate runs: the daily GitHub Actions cron (Phase 6)
starts a fresh process every time, so an in-memory checkpointer would lose
a tender's "paused for approval" state the moment that process exits.
Persisting checkpoints to the same Supabase Postgres instance everything
else already uses avoids standing up a second storage system.
"""

from __future__ import annotations

from collections.abc import Iterator
from contextlib import contextmanager

from langgraph.checkpoint.postgres import PostgresSaver
from psycopg import Connection
from psycopg.rows import dict_row

from tendersathi import config


@contextmanager
def get_checkpointer() -> Iterator[PostgresSaver]:
    """Open a `PostgresSaver` against `DATABASE_URL`, creating its tables if needed.

    Connects directly instead of via `PostgresSaver.from_conn_string` (which
    hardcodes `prepare_threshold=0`, i.e. prepare every statement):
    `DATABASE_URL` points at Supabase's transaction-mode pooler, which
    multiplexes many clients onto a handful of real server connections and
    doesn't reliably clear server-side prepared statements between them, so
    a second process (the API server restarting, or a cron run overlapping
    the API) can collide with another client's statement of the same
    autogenerated name (`psycopg.errors.DuplicatePreparedStatement`).
    `prepare_threshold=None` disables prepared statements outright, which
    costs nothing here since each checkpoint query runs once per request,
    not in a tight loop where preparing would pay off.

    `.setup()` runs PostgresSaver's own migrations; it tracks its schema
    version in the database and is safe to call on every connect, not just
    the first one.
    """
    if not config.DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL must be set in .env to checkpoint the LangGraph pipeline "
            "(Supabase dashboard -> Project Settings -> Database -> Connection string)."
        )
    with Connection.connect(
        config.DATABASE_URL, autocommit=True, prepare_threshold=None, row_factory=dict_row
    ) as conn:
        checkpointer = PostgresSaver(conn)
        checkpointer.setup()
        yield checkpointer
